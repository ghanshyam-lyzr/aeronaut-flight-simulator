import { chmod, mkdir, readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { terrainCpp } from './terrain-cpp.js';
import { STATE, PARAMS, CONTROLS, WIND, IMPACT, fieldName } from '../src/wasm/schema.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const generated = new URL('../native/generated/', import.meta.url);
await mkdir(generated, { recursive: true });
// The lake shader already expands the region/airport data. Compile that same
// arithmetic as C++ doubles, so changing a region cannot leave stale native data.
const terrain = terrainCpp();
await writeFile(new URL('terrain.h', generated), `// Generated from terrain.js groundShader. Do not edit.\nnamespace terrain {\n${terrain}\n}\n`);
const structs = { State: STATE, Params: PARAMS, Controls: CONTROLS, Wind: WIND, Impact: IMPACT };
const abi = Object.entries(structs).map(([name, fields]) => `struct ${name} {\n${fields.map(k => `  double ${fieldName(k)};`).join('\n')}\n};\nstatic_assert(sizeof(${name}) == ${fields.length} * sizeof(double));`).join('\n');
await writeFile(new URL('abi.h', generated), `// Generated from src/wasm/schema.js. Do not edit.\n${abi}\n`);
// Generate direct property access instead of megamorphic per-field loops in
// the frame loop. The schema remains the only authority for struct offsets.
const access = path => 'f.' + path.replace(/\.(\d+)/g, '[$1]');
const bools = new Set(['afterburner','gearDown','crashed','stalled','grounded','autopilot','headingHold','recovering']);
const paramValues = {
  afterburnerFrom: 'f.afterburnerFrom ?? -1', yawResponse: 'f.yawResponse ?? (f.rotorcraft ? 6 : f.pitchResponse)',
  pitchMin: 'f.pitchLimits?.[0] ?? 0', pitchMax: 'f.pitchLimits?.[1] ?? 0', idleSink: 'f.idleSink ?? 6',
  levelRate: 'f.levelRate ?? 1.6', groundClearance: 'f.rotorcraft ? f.groundClearance : flight.type.groundClearance ?? 2.8',
  brakeDeceleration: 'brakes', footprintX: 'f.footprint?.[0] ?? 1.2', footprintZ: 'f.footprint?.[1] ?? 1.2',
};
const bindings = `// Generated by scripts/build-wasm.js from schema.js. Do not edit.\nexport function packState(f, b) {\n${STATE.map((path,i) => `  b[${i}] = ${access(path)} ?? 0;`).join('\n')}\n}\nexport function unpackState(f, b) {\n${STATE.filter(path => path !== 'state.selectedHeading').map(path => { const i=STATE.indexOf(path); return `  ${access(path)} = ${bools.has(path.split('.').at(-1)) ? '!!' : ''}b[${i}];`; }).join('\n')}\n}\nexport function packParams(flight, b, brakes) {\n  const f = flight.type.flight;\n${PARAMS.map((path,i) => `  b[${i}] = ${paramValues[path] ?? `f.${path} ?? 0`};`).join('\n')}\n}\n`;
const bindingsURL = new URL('../src/wasm/bindings.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(bindingsURL,'utf8') !== bindings) throw new Error('WASM bindings are stale. Run npm run build:wasm.');
} else await writeFile(bindingsURL, bindings);

const args = [
  'native/engine.cpp', '-o', 'src/wasm/engine.wasm', '-std=c++17', '-O3', '-flto',
  '-fno-exceptions', '-fno-rtti', '-ffp-contract=off', '--no-entry', '-sSTANDALONE_WASM=1',
  '-sFILESYSTEM=0', '-sMALLOC=none', '-sINITIAL_MEMORY=2097152', '-sSTACK_SIZE=65536',
  '-sEXPORTED_FUNCTIONS=["_abi_version","_flight_state","_flight_params","_flight_controls","_flight_wind","_flight_impact","_flight_update","_terrain_height","_height_buffer","_height_grid"]',
];
const compiler = process.env.EMXX ?? 'em++';
if (!process.argv.includes('--check')) {
  const result = spawnSync(compiler, args, { cwd: root, stdio: 'inherit' });
  if (result.error?.code === 'ENOENT') throw new Error('Install Emscripten 3.1.64 and source emsdk_env.sh, or set EMXX to em++. See docs/webassembly.md.');
  if (result.status !== 0) process.exit(result.status ?? 1);
  await chmod(new URL('../src/wasm/engine.wasm', import.meta.url), 0o644);
}
const inputs = ['native/engine.cpp', 'src/terrain.js', 'src/regions.js', 'src/airports.js', 'src/airfield.js', 'src/wasm/schema.js', 'scripts/build-wasm.js', 'scripts/terrain-cpp.js'];
const hash = createHash('sha256');
for (const path of inputs) hash.update(await readFile(new URL(`../${path}`, import.meta.url)));
const source = hash.digest('hex');
const binary = createHash('sha256').update(await readFile(new URL('../src/wasm/engine.wasm', import.meta.url))).digest('hex');
const manifest = JSON.stringify({ source, binary }, null, 2) + '\n';
const manifestURL = new URL('../src/wasm/engine.manifest.json', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(manifestURL, 'utf8') !== manifest) throw new Error('C++ WebAssembly is stale. Run npm run build:wasm with Emscripten.');
  console.log('WebAssembly source and binary checksums match.');
} else {
  await writeFile(manifestURL, manifest);
  console.log('Built optimized C++ WebAssembly engine.');
}
